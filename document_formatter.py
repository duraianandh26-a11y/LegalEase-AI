import re
from html import escape


def sanitize_text(text: str) -> str:
    """
    Clean AI-generated text for display and export.
    """

    if not text:
        return ""

    replacements = {
        "“": '"',
        "”": '"',
        "‘": "'",
        "’": "'",
        "–": "-",
        "—": "-",
        "\t": " "
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


def extract_terms(terms_text: str) -> list:
    """
    Convert semicolon-separated terms into a list.
    """

    if not terms_text:
        return []

    return [
        term.strip()
        for term in terms_text.split(";")
        if term.strip()
    ]


def format_html_preview(text: str) -> str:
    """
    Create a styled HTML preview for Streamlit.
    """

    text = sanitize_text(text)

    paragraphs = text.split("\n")

    html_parts = []

    for para in paragraphs:

        para = para.strip()

        if not para:
            continue

        if len(para) < 80:
            html_parts.append(
                f"<h3>{escape(para)}</h3>"
            )
        else:
            html_parts.append(
                f"<p>{escape(para)}</p>"
            )

    html_content = "".join(html_parts)

    return f"""
    <div style="
        background:#1e1e1e;
        color:white;
        padding:25px;
        border-radius:12px;
        line-height:1.8;
        max-height:700px;
        overflow-y:auto;
        border:1px solid #444;
    ">
        {html_content}
    </div>
    """


def create_txt_content(
    document_type: str,
    parties: str,
    effective_date: str,
    content: str
) -> str:
    """
    Generate TXT document content.
    """

    return f"""
LEGAL DOCUMENT

Document Type:
{document_type}

Parties:
{parties}

Effective Date:
{effective_date}

{'=' * 60}

{content}

{'=' * 60}

Generated by LegalEase
AI-Powered Legal Document Generator
"""


def build_document_metadata(
    document_type: str,
    parties: str,
    effective_date: str
) -> dict:
    """
    Metadata used by PDF and DOCX generators.
    """

    return {
        "document_type": document_type,
        "parties": parties,
        "effective_date": effective_date
    }